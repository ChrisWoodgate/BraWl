#!/usr/bin/env python3
"""Neighbour tables for the ideal hcp lattice in BraWl.

The ideal hcp lattice is represented in BraWl by the hexagonal
primitive cell with lattice vectors (in units of the in-plane lattice
parameter a)

    a_1 = ( 1,         0, 0 )
    a_2 = (-1/2, sqrt(3)/2, 0 )
    a_3 = ( 0,         0, c ),   c/a = sqrt(8/3)

and two basis atoms at fractional coordinates

    atom 1: (1/3, 2/3, 1/4)
    atom 2: (2/3, 1/3, 3/4).

A lattice site is addressed as config(b, i, j, k), with b the basis
index and (i, j, k) the cell index along a_1, a_2, a_3. The neighbours
of a site on a given coordination shell are listed as offsets
(b', di, dj, dk), where b' is the basis index of the neighbour and
(di, dj, dk) is the cell offset. These offsets depend on the basis
index of the central atom, so each table carries one list per
sublattice.

Usage
-----
Print the Fortran parameter tables for shells 1 to N:

    python ideal_hcp_neighbour_tables.py --fortran N

Check that the tables hard-coded in Fortran source files match a
brute-force enumeration (exit status 0 on success, 1 on failure):

    python ideal_hcp_neighbour_tables.py --check src/random_site.f90 \\
        src/bw_hamiltonian.f90

Authors: C. D. Woodgate, Claude Fable 5.1 (2026)
"""

import argparse
import itertools
import re
import sys
from fractions import Fraction

# Fractional coordinates of the two basis atoms
BASIS = (
    (Fraction(1, 3), Fraction(2, 3), Fraction(1, 4)),
    (Fraction(2, 3), Fraction(1, 3), Fraction(3, 4)),
)

# Squared axial ratio (c/a)^2 for the ideal lattice
C_OVER_A_SQ = Fraction(8, 3)


def dist_sq(x, y, z):
    """Squared length (units of a^2) of x a_1 + y a_2 + z a_3.

    Uses the metric a_1.a_1 = a_2.a_2 = 1, a_1.a_2 = -1/2,
    a_3.a_3 = (c/a)^2, a_1.a_3 = a_2.a_3 = 0, so the result is exact.
    """
    return x * x + y * y - x * y + C_OVER_A_SQ * z * z


def enumerate_shells(n_shells, reach=4):
    """Return (shell_d2, tables).

    shell_d2 is the list of squared shell radii (Fractions) for shells
    1..n_shells. tables[s][b0] is the sorted list of neighbour offsets
    (b, di, dj, dk) (1-based basis indices) of a central atom on
    sublattice b0 (1-based) on shell s (1-based).
    """
    by_dist = {0: {}, 1: {}}
    rng = range(-reach, reach + 1)
    for b0 in (0, 1):
        for b in (0, 1):
            for di, dj, dk in itertools.product(rng, rng, rng):
                dx = BASIS[b][0] - BASIS[b0][0] + di
                dy = BASIS[b][1] - BASIS[b0][1] + dj
                dz = BASIS[b][2] - BASIS[b0][2] + dk
                d2 = dist_sq(dx, dy, dz)
                if d2 == 0:
                    continue
                by_dist[b0].setdefault(d2, []).append((b + 1, di, dj, dk))
    d2_list = sorted(by_dist[0])
    assert d2_list == sorted(by_dist[1]), "sublattices differ"
    if len(d2_list) < n_shells + 1:
        raise RuntimeError("increase 'reach' to enumerate this many shells")
    shell_d2 = d2_list[:n_shells]
    # Guard: the enumeration box must comfortably contain every shell
    # requested, i.e. the furthest shell must be well inside the box.
    assert shell_d2[-1] < reach * reach, "increase 'reach'"
    tables = {}
    for s, d2 in enumerate(shell_d2, start=1):
        tables[s] = {b0 + 1: sorted(by_dist[b0][d2]) for b0 in (0, 1)}
    return shell_d2, tables


def fortran_table(name, shell, offsets, shell_d2, indent="  "):
    """Format one Fortran parameter array in the BraWl house style."""
    n = len(offsets[1])
    assert n == len(offsets[2])
    lines = []
    d2 = shell_d2[shell - 1]
    if d2 == 1:
        dist = "a"
    elif d2.denominator == 1:
        dist = f"sqrt({d2.numerator})*a"
    else:
        dist = f"sqrt({d2.numerator}/{d2.denominator})*a"
    lines.append(f"{indent}! Shell {shell} of the ideal hcp lattice: {n} "
                 f"neighbours at {dist}.")
    lines.append(f"{indent}! Entries are (basis index of the neighbour, "
                 "offset along a_1,")
    lines.append(f"{indent}! offset along a_2, offset along a_3), listed "
                 "first for a central")
    lines.append(f"{indent}! atom on basis site 1 and then for one on "
                 "basis site 2.")
    lines.append(f"{indent}! Generated by tests/ideal_hcp_neighbour_tables.py")
    head = f"{indent}integer, parameter, dimension(4,{n},2) ::"
    lines.append(head.ljust(71) + "&")
    lines.append(f"{indent}{name} = reshape((/".ljust(71) + "&")
    rows = []
    for b0 in (1, 2):
        for (b, di, dj, dk) in offsets[b0]:
            rows.append(f"{indent}  {b:2d}, {di:2d}, {dj:2d}, {dk:2d}")
    for r, row in enumerate(rows):
        last = r == len(rows) - 1
        if last:
            lines.append(f"{row}  /), (/4, {n}, 2/))")
        else:
            lines.append((row + ",").ljust(71) + "&")
    return "\n".join(lines)


def emit_fortran(n_shells):
    shell_d2, tables = enumerate_shells(n_shells)
    out = []
    for s in range(1, n_shells + 1):
        name = f"ideal_hcp_shell{s}_nbrs"
        out.append(fortran_table(name, s, tables[s], shell_d2))
        out.append("")
    print("\n".join(out))


TABLE_RE = re.compile(
    r"dimension\s*\(\s*4\s*,\s*(\d+)\s*,\s*2\s*\)\s*::\s*"
    r"(ideal_hcp\w*nbrs)\s*=\s*reshape\s*\(\s*\(/(.*?)/\)\s*,"
    r"\s*\(/\s*4\s*,\s*(\d+)\s*,\s*2\s*/\)\s*\)",
    re.DOTALL | re.IGNORECASE,
)


def parse_fortran_tables(path):
    """Return {name: (n, [ints])} for every ideal_hcp table in a file."""
    text = []
    with open(path) as f:
        for line in f:
            line = line.split("!", 1)[0]
            text.append(line.replace("&", " "))
    text = "\n".join(text)
    found = {}
    for m in TABLE_RE.finditer(text):
        n, name, body, n2 = m.group(1), m.group(2), m.group(3), m.group(4)
        if n != n2:
            raise ValueError(f"{name}: dimension {n} but reshape {n2}")
        ints = [int(v) for v in body.replace("\n", " ").split(",")]
        found[name.lower()] = (int(n), ints)
    return found


def shell_of(name):
    if name == "ideal_hcp_nbrs":
        return 1
    m = re.fullmatch(r"ideal_hcp_shell(\d+)_nbrs", name)
    if not m:
        raise ValueError(f"cannot infer shell from table name {name}")
    return int(m.group(1))


def check(paths):
    ok = True
    n_tables = 0
    for path in paths:
        tables = parse_fortran_tables(path)
        if not tables:
            print(f"{path}: no ideal_hcp neighbour tables found")
            continue
        max_shell = max(shell_of(nm) for nm in tables)
        shell_d2, ref = enumerate_shells(max_shell)
        for name, (n, ints) in tables.items():
            n_tables += 1
            s = shell_of(name)
            if len(ints) != 4 * n * 2:
                print(f"FAIL {path}:{name}: {len(ints)} values, expected "
                      f"{4 * n * 2}")
                ok = False
                continue
            # Fortran column-major order: first index fastest
            for b0 in (1, 2):
                base = (b0 - 1) * 4 * n
                got = [tuple(ints[base + 4 * k: base + 4 * k + 4])
                       for k in range(n)]
                exp = ref[s][b0]
                if len(set(got)) != len(got):
                    print(f"FAIL {path}:{name}: duplicate entries for "
                          f"central basis atom {b0}")
                    ok = False
                if sorted(got) != exp:
                    missing = sorted(set(exp) - set(got))
                    extra = sorted(set(got) - set(exp))
                    print(f"FAIL {path}:{name}: central basis atom {b0} "
                          f"differs from brute force (shell {s}, "
                          f"d^2 = {shell_d2[s - 1]})")
                    if missing:
                        print(f"     missing: {missing}")
                    if extra:
                        print(f"     extra:   {extra}")
                    ok = False
                else:
                    print(f"ok   {path}:{name}: central basis atom {b0}, "
                          f"shell {s}, {n} neighbours at d^2 = "
                          f"{shell_d2[s - 1]}")
    if n_tables == 0:
        print("no tables checked")
        ok = False
    return ok


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--fortran", type=int, metavar="N",
                    help="print Fortran tables for shells 1..N")
    ap.add_argument("--check", nargs="+", metavar="FILE",
                    help="check tables in Fortran source file(s)")
    ap.add_argument("--summary", type=int, metavar="N",
                    help="print distance and coordination of shells 1..N")
    args = ap.parse_args()
    if args.summary:
        shell_d2, tables = enumerate_shells(args.summary)
        print(" shell   d^2         d/a     coordination")
        for s, d2 in enumerate(shell_d2, start=1):
            print(f"  {s:4d}   {str(d2):8s}   {float(d2) ** 0.5:6.4f}  "
                  f"{len(tables[s][1]):4d}")
    if args.fortran:
        emit_fortran(args.fortran)
    if args.check:
        sys.exit(0 if check(args.check) else 1)


if __name__ == "__main__":
    main()
