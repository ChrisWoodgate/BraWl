  !> @brief   Subroutine to compute the periodically wrapped cell
  !>          indices around a site on the ideal hcp lattice
  !>
  !> @details Neighbours in the ideal hcp tables lie at most
  !>          ideal_hcp_max_offset cells from the central site in each
  !>          direction, so the wrapped cell index for every offset in
  !>          that range is computed once per site and then looked up
  !>          for each neighbour, rather than taking a modulo for every
  !>          neighbour on every shell.
  !>
  !> @author  C. D. Woodgate
  !> @author  Claude Fable 5.1
  !> @date    2026
  !>
  !> @param  setup Derived type containing simulation parameters
  !> @param  site_i Lattice vector index 1
  !> @param  site_j Lattice vector index 2
  !> @param  site_k Lattice vector index 3
  !> @param  w_1 Wrapped cell indices for offsets along a_1
  !> @param  w_2 Wrapped cell indices for offsets along a_2
  !> @param  w_3 Wrapped cell indices for offsets along a_3
  !>
  !> @return None
  subroutine ideal_hcp_wrap(setup, site_i, site_j, site_k,             &
                            w_1, w_2, w_3)

    class(run_params), intent(in) :: setup
    integer, intent(in) :: site_i, site_j, site_k
    integer, dimension(-ideal_hcp_max_offset:ideal_hcp_max_offset),    &
             intent(out) :: w_1, w_2, w_3
    integer :: d

    do d=-ideal_hcp_max_offset, ideal_hcp_max_offset
      w_1(d) = modulo(site_i + d - 1, setup%n_grid_1) + 1
      w_2(d) = modulo(site_j + d - 1, setup%n_grid_2) + 1
      w_3(d) = modulo(site_k + d - 1, setup%n_grid_3) + 1
    end do

  end subroutine ideal_hcp_wrap

  !> @brief   Function to compute the contribution to the simulation
  !>          energy made by an atom interacting with its neighbours
  !>          on one coordination shell of the ideal hcp lattice
  !>
  !> @details The neighbours are read from the column of the supplied
  !>          offset table for the sublattice of the central atom, and
  !>          their cell indices are wrapped into the simulation cell
  !>          using the arrays computed by ideal_hcp_wrap. This one
  !>          routine serves every shell; the tables differ.
  !>
  !> @author  C. D. Woodgate
  !> @author  Claude Fable 5.1
  !> @date    2026
  !>
  !> @param  config Current atomic configuration
  !> @param  species Species of the atom on the central site
  !> @param  nbrs Offset table for the shell, e.g. ideal_hcp_shell1_nbrs
  !> @param  shell Index of the coordination shell (selects the EPIs)
  !> @param  site_b Basis index of the central site (1 or 2)
  !> @param  w_1 Wrapped cell indices for offsets along a_1
  !> @param  w_2 Wrapped cell indices for offsets along a_2
  !> @param  w_3 Wrapped cell indices for offsets along a_3
  !>
  !> @return The contribution to the simulation energy made by an atom
  !>         interacting with its neighbours on the given shell
  function ideal_hcp_shell_energy(config, species, nbrs, shell,        &
                                  site_b, w_1, w_2, w_3) result(energy)

    integer(array_int), dimension(:,:,:,:), intent(in) :: config
    integer(array_int), intent(in) :: species
    integer, dimension(:,:,:), intent(in) :: nbrs
    integer, intent(in) :: shell, site_b
    integer, dimension(-ideal_hcp_max_offset:ideal_hcp_max_offset),    &
             intent(in) :: w_1, w_2, w_3
    real(real64) :: energy
    integer :: n

    energy = 0.0_real64

    do n=1, size(nbrs, 2)
      energy = energy + V_ex(species,                                  &
                             config(nbrs(1,n,site_b),                  &
                                    w_1(nbrs(2,n,site_b)),             &
                                    w_2(nbrs(3,n,site_b)),             &
                                    w_3(nbrs(4,n,site_b))),            &
                             shell)
    end do

  end function ideal_hcp_shell_energy

